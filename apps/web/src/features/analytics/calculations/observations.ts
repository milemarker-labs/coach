import type { ActivitySummary } from "@coach/shared";
import { formatDistance, formatDuration } from "@/lib/format.ts";
import type { DayKey } from "./dates.ts";
import { formStatus, type FitnessSummary } from "./load.ts";
import { compareWindows, percentChange } from "./volume.ts";

export type ObservationTone = "positive" | "negative" | "neutral";

export interface Observation {
  id: string;
  label: string;
  value: string;
  detail: string;
  tone: ObservationTone;
}

export function formatSigned(value: number, suffix = ""): string {
  const rounded = Math.round(value);
  return `${rounded > 0 ? "+" : rounded < 0 ? "−" : ""}${Math.abs(rounded)}${suffix}`;
}

/**
 * Deterministic comparisons for the Coach's Take card. Every value here is a plain
 * calculation over stored activities; nothing is generated by a model.
 */
export function buildObservations(activities: ActivitySummary[], today: DayKey, fitness: FitnessSummary | null): Observation[] {
  const { current, previous } = compareWindows(activities, today, 7);
  const items: Observation[] = [];

  if (current.count > 0 || previous.count > 0) {
    const distanceChange = percentChange(current.distance, previous.distance);
    items.push({
      id: "distance",
      label: "Distance vs previous 7 days",
      value: distanceChange == null ? formatDistance(current.distance) : formatSigned(distanceChange, "%"),
      detail: `${formatDistance(current.distance)} against ${formatDistance(previous.distance)}`,
      tone: distanceChange == null ? "neutral" : distanceChange >= 0 ? "positive" : "negative",
    });
    const timeChange = percentChange(current.movingTime, previous.movingTime);
    items.push({
      id: "time",
      label: "Moving time vs previous 7 days",
      value: timeChange == null ? formatDuration(current.movingTime) : formatSigned(timeChange, "%"),
      detail: `${formatDuration(current.movingTime)} against ${formatDuration(previous.movingTime)}`,
      tone: timeChange == null ? "neutral" : timeChange >= 0 ? "positive" : "negative",
    });
  }

  if (fitness) {
    const status = formStatus(fitness.current.form);
    items.push({
      id: "form",
      label: "Form",
      value: status.label,
      detail: `Fitness ${Math.round(fitness.current.fitness)}, fatigue ${Math.round(fitness.current.fatigue)}, form ${formatSigned(fitness.current.form)}`,
      tone: status.tone === "danger" || status.tone === "warning" ? "negative" : "neutral",
    });
  }
  return items;
}
